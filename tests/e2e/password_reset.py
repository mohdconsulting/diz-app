"""E2e test of e-mail at registration, "forgot password" and the reset link (diz_password_reset.sql).
Usage:  npm run build && python3 tests/e2e/password_reset.py"""
import asyncio, pathlib, sys
from playwright.async_api import async_playwright
R=pathlib.Path(__file__).resolve().parent.parent.parent; E=R/'tests/e2e'; URL=(R/'index.html').as_uri()
res=[]
def check(l,c): res.append(('PASS ' if c else '*** FAIL ')+l)
async def main():
    async with async_playwright() as p:
        b=await p.chromium.launch(); ctx=await b.new_context(viewport={'width':420,'height':900}); pg=await ctx.new_page()
        errs=[]; pg.on('pageerror',lambda e:errs.append(str(e)))
        await pg.add_init_script((E/'fake-webrtc.js').read_text())
        await pg.add_init_script("try{ if(!localStorage.getItem('diz_lang')) localStorage.setItem('diz_lang','en'); }catch(e){}")
        await pg.route('**/@supabase/supabase-js@2',lambda r:r.fulfill(body=(E/'fake-supabase.js').read_text(),content_type='application/javascript'))
        await pg.route('**/fonts.g*/**',lambda r:r.abort())
        await pg.route('**/leaflet@*/**',lambda r:r.fulfill(body='',content_type='application/javascript'))
        await pg.goto(URL); await pg.wait_for_timeout(800)
        # register: e-mail field shown and required
        await pg.click('#authSwitchBtn')
        check('email field on register', await pg.is_visible('#authEmailInput'))
        check('forgot link hidden on register', not await pg.is_visible('#authForgotBtn'))
        await pg.fill('#authNameInput','Ali'); await pg.fill('#authPhoneInput','0770111'); await pg.fill('#authPassInput','secret1')
        await pg.click('#authRoleChips .chip[data-val=customer]')
        await pg.fill('#authEmailInput','not-an-email'); await pg.click('#authSubmitBtn'); await pg.wait_for_timeout(400)
        check('bad email blocks register', await pg.is_visible('#authOverlay'))
        await pg.fill('#authEmailInput','Ali@Example.com'); await pg.click('#authSubmitBtn'); await pg.wait_for_timeout(700)
        check('registered', not await pg.is_visible('#authOverlay'))
        check('email stored', await pg.evaluate("JSON.parse(sessionStorage.getItem('dbs')).db.users.find(u=>u.phone==='0770111').email")=='ali@example.com')
        check('no nudge when email exists', not await pg.is_visible('#emailNudge'))
        uid=await pg.evaluate("JSON.parse(sessionStorage.getItem('dbs')).db.users.find(u=>u.phone==='0770111').id")
        await pg.click('#logoutBtn'); await pg.wait_for_timeout(300)
        # forgot password
        await pg.fill('#authPhoneInput','0770111')
        check('forgot link on login', await pg.is_visible('#authForgotBtn'))
        await pg.click('#authForgotBtn')
        check('forgot panel', await pg.is_visible('#authForgotWrap') and not await pg.is_visible('#authMainWrap'))
        check('phone prefilled', await pg.input_value('#forgotPhoneInput')=='0770111')
        await pg.click('#forgotSendBtn'); await pg.wait_for_timeout(300)
        calls=await pg.evaluate("window.__fnCalls")
        check('function called with phone+lang', calls==[{'name':'request-password-reset','body':{'phone':'0770111','lang':'en'}}])
        check('sent note shown', 'spam' in await pg.inner_text('#forgotNote'))
        await pg.click('#forgotBackBtn'); check('back to login', await pg.is_visible('#authMainWrap'))
        # bad link
        await pg.goto(URL+'?reset_token=tok-wrong&lang=en'); await pg.wait_for_timeout(800)
        check('bad token: login shown', await pg.is_visible('#authMainWrap'))
        check('bad token: param removed', 'reset_token' not in pg.url)
        # good link
        await pg.goto(URL+'?reset_token=tok-'+uid+'&lang=en'); await pg.wait_for_timeout(800)
        check('reset panel shown', await pg.is_visible('#authResetWrap') and not await pg.is_visible('#authMainWrap'))
        check('token removed from url', 'reset_token' not in pg.url)
        await pg.fill('#resetNewInput','newpass1'); await pg.fill('#resetRepeatInput','other12'); await pg.click('#resetSaveBtn'); await pg.wait_for_timeout(300)
        check('mismatch blocks', await pg.is_visible('#authResetWrap'))
        await pg.fill('#resetRepeatInput','newpass1'); await pg.click('#resetSaveBtn'); await pg.wait_for_timeout(700)
        check('signed in after reset', not await pg.is_visible('#authOverlay'))
        await pg.click('#logoutBtn'); await pg.wait_for_timeout(300)
        await pg.fill('#authPhoneInput','0770111'); await pg.fill('#authPassInput','newpass1'); await pg.click('#authSubmitBtn'); await pg.wait_for_timeout(700)
        check('login with new password', not await pg.is_visible('#authOverlay'))
        # e-mail is optional: account without e-mail is not nagged, and it can be added/removed in my details
        await pg.evaluate("(()=>{const s=JSON.parse(sessionStorage.getItem('dbs')); s.db.users.find(u=>u.phone==='0770111').email=null; sessionStorage.setItem('dbs',JSON.stringify(s));})()")
        await pg.reload(); await pg.wait_for_timeout(900)
        check('no nudge without email', not await pg.is_visible('#emailNudge'))
        await pg.evaluate("goTo('mine')"); await pg.wait_for_timeout(300)
        await pg.fill('#accountEmailInput','x'); await pg.click('#accountSaveBtn'); await pg.wait_for_timeout(300)
        check('bad email not saved', await pg.evaluate("JSON.parse(sessionStorage.getItem('dbs')).db.users.find(u=>u.phone==='0770111').email") is None)
        await pg.fill('#accountEmailInput','ali2@example.com'); await pg.click('#accountSaveBtn'); await pg.wait_for_timeout(400)
        check('email saved from profile', await pg.evaluate("JSON.parse(sessionStorage.getItem('dbs')).db.users.find(u=>u.phone==='0770111').email")=='ali2@example.com')
        await pg.fill('#accountEmailInput',''); await pg.click('#accountSaveBtn'); await pg.wait_for_timeout(400)
        check('email can be removed', await pg.evaluate("JSON.parse(sessionStorage.getItem('dbs')).db.users.find(u=>u.phone==='0770111').email") is None)
        # register without e-mail
        await pg.click('#logoutBtn'); await pg.wait_for_timeout(300)
        await pg.click('#authSwitchBtn')
        await pg.fill('#authNameInput','Sara'); await pg.fill('#authPhoneInput','0770222'); await pg.fill('#authPassInput','secret1')
        await pg.click('#authRoleChips .chip[data-val=customer]')
        await pg.click('#authSubmitBtn'); await pg.wait_for_timeout(700)
        check('register without email', not await pg.is_visible('#authOverlay'))
        check('no email stored', not await pg.evaluate("JSON.parse(sessionStorage.getItem('dbs')).db.users.find(u=>u.phone==='0770222').email"))
        check('no nudge for new user without email', not await pg.is_visible('#emailNudge'))
        # arabic texts render
        await pg.click('#logoutBtn'); await pg.wait_for_timeout(300)
        await pg.click('#authLangSwitch button[data-lang=ar]'); await pg.wait_for_timeout(200)
        await pg.click('#authForgotBtn'); await pg.wait_for_timeout(200)
        check('arabic forgot title', await pg.inner_text('#authTitle')=='إعادة تعيين كلمة المرور')
        check('no page errors', not errs)
        if errs: print(errs)
        await b.close()
asyncio.run(main())
print('\n'.join(res))
sys.exit(1 if any(r.startswith('***') for r in res) else 0)
